"""Refuse an upload-artifact step without a short, explicit retention.

Every actions/upload-artifact step of a workflow this repository writes must
name retention-days as a literal integer from 1 to MAX_DAYS, so that no
artifact falls back to the repository default (90 days). release.yml is
generated by the maelys-release socle and is not read here.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
MAX_DAYS = 14
GENERATED = {'release.yml'}
UPLOAD = re.compile(r'^(\s*)(-\s+)?uses:\s*actions/upload-artifact@')
STEP = re.compile(r'^(\s*)-\s')
RETENTION = re.compile(r'^\s*retention-days:\s*(.*?)\s*(#.*)?$')


def indent(line):
    return len(line) - len(line.lstrip(' '))


def step_bounds(lines, at):
    """Return the [start, end) lines of the list item holding line `at`."""
    start = at
    while start >= 0 and not (STEP.match(lines[start]) and indent(lines[start]) <= indent(lines[at])):
        start -= 1
    if start < 0:
        raise ValueError(f'line {at + 1}: upload-artifact outside a step')
    end = start + 1
    while end < len(lines):
        text = lines[end].strip()
        if text and not text.startswith('#') and indent(lines[end]) <= indent(lines[start]):
            break
        end += 1
    return start, end


def check(path):
    lines = path.read_text().splitlines()
    errors = []
    for at, line in enumerate(lines):
        if not UPLOAD.match(line):
            continue
        start, end = step_bounds(lines, at)
        values = [m.group(1) for m in map(RETENTION.match, lines[start:end]) if m]
        where = f'{path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}:{at + 1}'
        if not values:
            errors.append(f'{where}: upload-artifact without retention-days')
        elif not re.fullmatch(r'[0-9]+', values[0].strip('\'"')):
            errors.append(f'{where}: retention-days must be a literal integer, not {values[0]}')
        elif not 1 <= int(values[0].strip('\'"')) <= MAX_DAYS:
            errors.append(f'{where}: retention-days {values[0]} is outside 1..{MAX_DAYS}')
    return errors


def workflows(directory):
    return sorted(p for p in directory.iterdir()
                  if p.suffix in ('.yml', '.yaml') and p.name not in GENERATED)


def main(argv):
    directory = Path(argv[1]) if len(argv) > 1 else ROOT / '.github/workflows'
    files = workflows(directory)
    errors = [error for path in files for error in check(path)]
    for error in errors:
        print(f'error: {error}', file=sys.stderr)
    if not errors:
        print(f'artifact retention: every upload in {len(files)} workflows keeps 1..{MAX_DAYS} days')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
